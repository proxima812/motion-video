# Luminance map of each TatAvatar photo as it sits on screen (540x590 box, contain, bottom center, FIT scale),
# composited over white -> src/kit/avatarLuma.ts. Glass word pills use it to pick black or white text.
from PIL import Image
import glob, os
W, H, CELL = 540, 590, 10
FIT = {"kalpak-green": 1.18, "portrait-traditional": 1.18}  # keep in sync with FIT in src/kit/TatAvatar.tsx
out = {}
for p in sorted(glob.glob("public/tatarverse/avatar/*.png")):
    name = os.path.basename(p)[:-4]
    im = Image.open(p).convert("RGBA")
    k = min(W / im.width, H / im.height)
    fit = FIT.get(name, 1)
    rows = []
    for gy in range(H // CELL):
        row = ""
        for gx in range(W // CELL):
            lx, ly = gx * CELL + CELL / 2, gy * CELL + CELL / 2
            lx2, ly2 = W / 2 + (lx - W / 2) / fit, H + (ly - H) / fit  # undo FIT (origin bottom center)
            ix, iy = (lx2 - (W - im.width * k) / 2) / k, (ly2 - (H - im.height * k)) / k
            lum = 1.0
            if 0 <= ix < im.width and 0 <= iy < im.height:
                r, g, b, a = im.getpixel((int(ix), int(iy)))
                y = (0.2126 * r + 0.7152 * g + 0.0722 * b) / 255
                lum = y * a / 255 + (1 - a / 255)
            row += "0123456789"[min(9, int(lum * 10))]
        rows.append(row)
    out[name] = rows
L = ["// Generated by scripts/avatar-luma.py: luminance (0-9) of each avatar photo over white,",
     f"// {CELL}px cells over the {W}x{H} TatAvatar box (row = y). Used by the glass word pills.",
     f"export const LUMA_CELL = {CELL};", "export const AVATAR_LUMA: Record<string, string[]> = {"]
for n, rows in out.items():
    L.append(f'  "{n}": [' + ", ".join(f'"{r}"' for r in rows) + "],")
L += ["};", ""]
open("src/kit/avatarLuma.ts", "w").write("\n".join(L))
print({n: len(r) for n, r in out.items()})
