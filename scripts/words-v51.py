# Two hosts: spoken words with absolute frames (60 fps) per host -> src/v51/words.ts; prints VO starts and word frames.
# Odd lines = Ahu, even lines = Alicja. GAP[i] = frames between line i+1 and line i+2 (dialog pacing).
import json, re, subprocess
GAP = [10, 12, 18, 10, 18, 12, 16, 16, 20, 12, 20, 10]
MERGE = [(["Татарверс", "точка", "си", "си"], "tatarverse.cc"), (["Четыреста", "десять"], "410"), (["пятидесяти", "трех"], "53"), (["Сто", "пятьдесят", "одна"], "151")]
f, vo, words = 8, [], {"ahu": [], "alicja": []}
for i in range(1, 14):
    d = float(subprocess.check_output(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", f"public/v51/vo/l{i}.mp3"]))
    dur = round(d * 60); vo.append((f, dur)); who = "ahu" if i % 2 else "alicja"
    a = json.load(open(f"public/v51/vo/l{i}.json"))
    cur, t, inside, line = "", 0.0, False, []
    for c, s in list(zip(a["characters"], a["character_start_times_seconds"])) + [(" ", 0)]:
        if c == "[": inside = True
        if inside:
            if c == "]": inside = False
            continue
        if c.isspace():
            w = re.sub(r"[^\w-]", "", cur).strip("-").replace("ё", "е").replace("Ё", "Е")
            if w: line.append((f + round(t * 60), w))
            cur = ""
        else:
            if not cur: t = s
            cur += c
    # one subtitle pill for the domain and spoken numbers; the rest of the group stays a silent nod ("")
    for seq, rep in MERGE:
        for k in range(len(line) - len(seq) + 1):
            if [w for _, w in line[k:k + len(seq)]] == seq:
                line[k:k + len(seq)] = [(line[k][0], rep)] + [(x, "") for x, _ in line[k + 1:k + len(seq)]]
    words[who] += line
    print(f"l{i} {who} from {f} dur {dur}:", " ".join(f"{w}@{x}" for x, w in line))
    f += dur + (GAP[i - 1] if i <= len(GAP) else 0)
print("last line ends", f)
print("VO = [" + ", ".join(f'{{ src: "v51/vo/l{i}.mp3", from: {s}, dur: {d} }}' for i, (s, d) in enumerate(vo, 1)) + "]")
L = ["// Generated by scripts/words-v51.py: every spoken word per host, absolute frame of its first letter.", "import type { SpokenWord } from \"../kit/TatAvatar\";", ""]
for who, name in (("ahu", "WORDS_AHU"), ("alicja", "WORDS_ALICJA")):
    L += [f"export const {name}: SpokenWord[] = ["] + [f'  {{ f: {x}, w: "{w}" }},' for x, w in words[who]] + ["];", ""]
open("src/v51/words.ts", "w").write("\n".join(L))
print(len(words["ahu"]), len(words["alicja"]))
