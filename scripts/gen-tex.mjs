// TeX -> self-contained SVG paths (MathJax 3, glyphs as paths, fill = currentColor), for any reel.
// usage: bun scripts/gen-tex.mjs <formulas.json> <out.ts>   (formulas.json: { "name": "TeX source", ... })
// mathjax-full is not a project dependency: install it once in a scratch dir and run the script from there:
//   mkdir -p /tmp/mj && cd /tmp/mj && echo '{}' > package.json && bun add mathjax-full@3
//   cp <repo>/scripts/gen-tex.mjs /tmp/mj/ && bun /tmp/mj/gen-tex.mjs <repo>/src/vN/tex.json <repo>/src/vN/tex.ts
import { readFileSync, writeFileSync } from "node:fs";
import { mathjax } from "mathjax-full/js/mathjax.js";
import { TeX } from "mathjax-full/js/input/tex.js";
import { SVG } from "mathjax-full/js/output/svg.js";
import { liteAdaptor } from "mathjax-full/js/adaptors/liteAdaptor.js";
import { RegisterHTMLHandler } from "mathjax-full/js/handlers/html.js";
import { AllPackages } from "mathjax-full/js/input/tex/AllPackages.js";

const [src, dst] = process.argv.slice(2);
const F = JSON.parse(readFileSync(src, "utf8"));
const adaptor = liteAdaptor();
RegisterHTMLHandler(adaptor);
const doc = mathjax.document("", { InputJax: new TeX({ packages: AllPackages }), OutputJax: new SVG({ fontCache: "none" }) });

const out = {};
for (const [k, tex] of Object.entries(F)) {
  const svg = adaptor.innerHTML(doc.convert(tex, { display: true }));
  const vb = svg.match(/viewBox="([^"]+)"/)[1];
  const body = svg
    .replace(/^<svg[^>]*>/, "")
    .replace(/<\/svg>$/, "")
    .replace(/ data-(mml-node|c|mjx-texclass|latex)="[^"]*"/g, "")
    .replace(/<title[^>]*>.*?<\/title>/g, "");
  if (body.includes("<use")) throw new Error(`${k}: font cache refs left`);
  out[k] = { vb, body };
}
const ts = `// Generated by scripts/gen-tex.mjs from tex.json. Do not edit.\n` +
  `export const TEX = ${JSON.stringify(out)} as const;\nexport type TexName = keyof typeof TEX;\n`;
writeFileSync(dst, ts);
console.log(`${dst}: ${Object.keys(out).length} formulas, ${(ts.length / 1024).toFixed(0)} KB`);
