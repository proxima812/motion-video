# Spoken words with absolute frames (60 fps) for the avatar word bubbles -> src/v18/words.ts
import json, re
VO_FROM = [10, 226, 712, 1155, 1559, 1942, 2312, 2536, 2847]
out = []
for i, base in enumerate(VO_FROM, 1):
    a = json.load(open(f"public/v18/vo/l{i}.json"))
    cur, t, inside = "", 0.0, False
    for c, s in list(zip(a["characters"], a["character_start_times_seconds"])) + [(" ", 0)]:
        if c == "[": inside = True
        if inside:
            if c == "]": inside = False
            continue
        if c.isspace():
            w = re.sub(r"[^\w-]", "", cur).replace("ё", "е").replace("Ё", "Е")
            if w: out.append((base + round(t * 60), w))
            cur = ""
        else:
            if not cur: t = s
            cur += c
# the domain is spoken as words: show it as written
SHOW = {"Татарлар": "tatarlar", "ка-зэ": ".kz"}
out = [(f, SHOW.get(w, w)) for f, w in out if w != "точка"]
L = ["// Generated by scripts/words-v18.py: every spoken word, absolute frame of its first letter.", "export const WORDS = ["]
L += [f'  {{ f: {f}, w: "{w}" }},' for f, w in out] + ["];", ""]
open("src/v18/words.ts", "w").write("\n".join(L))
print(len(out))
