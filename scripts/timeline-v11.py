# Builds src/vN/timeline.ts for the AlmatyDa booking pair (11 RU, 12 EN) from trimmed VO durations + word offsets
# (frames inside each line, from public/vN/vo/l*.json). Usage: python3 scripts/timeline-v11.py 11|12
import subprocess, sys
n = sys.argv[1]
title = {"11": "AlmatyDa booking (RU)", "12": "AlmatyDa booking (EN)"}[n]
B = {  # line -> {beat: offset in frames inside the line, measured at tempo 1.1; scaled to TEMPO below}
 "11": [{"hookBook": 116, "noDb": 247}, {"rooms": 194, "apartx": 338}, {"ws": 100, "rest": 247},
        {"server": 52, "browser": 155}, {"plexy": 68, "link": 146, "auth": 360},
        {"webhook": 52, "check": 135, "free": 205, "taken": 325}, {"state": 2, "zero": 216, "tests": 286}],
 "12": [{"hookBook": 116, "noDb": 255}, {"rooms": 164, "apartx": 286}, {"ws": 122, "rest": 249},
        {"server": 20, "browser": 190}, {"plexy": 59, "link": 151, "auth": 391},
        {"webhook": 52, "check": 120, "free": 212, "taken": 356}, {"state": 2, "zero": 212, "tests": 295}],
}[n]
TEMPO, GAP = 1.2, 12
ins = [None, "siteIn", "ddpIn", "priceIn", "payIn", "hookIn", "endIn"]
f, vo, beats = 8, [], {}
for i in range(7):
    d = round(float(subprocess.check_output(["ffprobe","-v","error","-show_entries","format=duration","-of","csv=p=0",f"public/v{n}/vo/l{i+1}.mp3"]))*60)
    vo.append((f, d))
    if ins[i]: beats[ins[i]] = f - 6
    for k, o in B[i].items(): beats[k] = f + round(o * 1.1 / TEMPO)
    f += d + GAP
dur = vo[-1][0] + vo[-1][1] + 40
L = [f"// Video {n} - {title}. Single source of truth for timing (60 fps).",
     f"// Generated by scripts/timeline-v11.py from public/v{n}/vo (Kyle, Eleven v4, trimmed x1.2 by scripts/trim-vo.py).",
     "export const F = {", f"  duration: {dur},"] + [f"  {k}: {v}," for k, v in beats.items()] + ["};", "", "export const VO = ["]
L += [f'  {{ src: "v{n}/vo/l{i+1}.mp3", from: {a}, dur: {d} }},' for i, (a, d) in enumerate(vo)] + ["];", ""]
open(f"src/v{n}/timeline.ts", "w").write("\n".join(L))
print(dur)
