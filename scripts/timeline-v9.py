# Builds src/vN/timeline.ts for the Astro 7.4 pair from trimmed VO durations + word offsets (frames, from /tmp words dump)
import subprocess, sys
n, title = sys.argv[1], sys.argv[2]
B = {  # line -> {beat: offset in frames inside the line}
 "9":  [{"hookQ":124}, {"cmd":203,"phases":412}, {"promise":124,"cut":249,"half":415}, {"workers":262,"cores":334},
        {"split":89,"cf":295}, {"e1":50,"e2":220,"e3":290}, {"node":129,"first":262,"astro":349}],
 "10": [{"hookQ":98}, {"cmd":194,"phases":404}, {"promise":133,"cut":185,"half":430}, {"workers":264,"cores":356},
        {"split":85,"cf":281}, {"e1":63,"e2":207,"e3":299}, {"node":129,"first":251,"astro":334}],
}[n]
ins = [None, "timingsIn", "promiseIn", "parallelIn", "imagesIn", "extrasIn", "nodeIn"]
f, vo, beats = 8, [], {}
for i in range(7):
    d = round(float(subprocess.check_output(["ffprobe","-v","error","-show_entries","format=duration","-of","csv=p=0",f"public/v{n}/vo/l{i+1}.mp3"]))*60)
    vo.append((f, d))
    if ins[i]: beats[ins[i]] = f - 6
    for k, o in B[i].items(): beats[k] = f + o
    if i == 3: beats["parallelEnd"] = f + d
    f += d + 16
dur = vo[-1][0] + vo[-1][1] + 40
L = [f"// Video {n} - {title}. Single source of truth for timing (60 fps).",
     f"// Generated by scripts/timeline-v9.py from public/v{n}/vo (Kyle, Eleven v4, trimmed x1.1 by scripts/trim-vo.py).",
     "export const F = {", f"  duration: {dur},"] + [f"  {k}: {v}," for k, v in beats.items()] + ["};", "", "export const VO = ["]
L += [f'  {{ src: "v{n}/vo/l{i+1}.mp3", from: {a}, dur: {d} }},' for i, (a, d) in enumerate(vo)] + ["];", ""]
open(f"src/v{n}/timeline.ts", "w").write("\n".join(L))
print(dur)
