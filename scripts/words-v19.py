# Video 19: VO placement (gap 16 frames) + every spoken word with its absolute frame (60 fps)
# -> src/v19/words.ts (avatar word pills) and a printout of word frames for timeline beats.
import json, re, subprocess
GAP, f, VO_FROM, DURS, out = 16, 8, [], [], []
# spoken form -> on-screen form for the pills
SHOW = {"татарверс": "tatarverse", "Татарверс": "tatarverse", "си": None, "точка": None, "пэ-дэ-эф": "PDF"}
for i in range(1, 9):
    d = float(subprocess.check_output(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", f"public/v19/vo/l{i}.mp3"]))
    VO_FROM.append(f); DURS.append(round(d * 60))
    a = json.load(open(f"public/v19/vo/l{i}.json"))
    cur, t, inside, line = "", 0.0, False, []
    for c, s in list(zip(a["characters"], a["character_start_times_seconds"])) + [(" ", 0)]:
        if c == "[": inside = True
        if inside:
            if c == "]": inside = False
            continue
        if c.isspace():
            w = re.sub(r"[^\w-]", "", cur).replace("ё", "е").replace("Ё", "Е")
            if w and w != "-":
                line.append((f + round(t * 60), w))
            cur = ""
        else:
            if not cur: t = s
            cur += c
    print(f"l{i} from={f} dur={DURS[-1]}:", " ".join(f"{w}:{fr}" for fr, w in line))
    for fr, w in line:
        sw = SHOW.get(w, w)
        if sw == "tatarverse": out.append((fr, "tatarverse.cc"))
        elif sw: out.append((fr, sw))
    f += DURS[-1] + GAP
print("end", f - GAP)
L = ["// Generated by scripts/words-v19.py: every spoken word, absolute frame of its first letter.", "export const WORDS = ["]
L += [f'  {{ f: {fr}, w: "{w}" }},' for fr, w in out] + ["];", ""]
open("src/v19/words.ts", "w").write("\n".join(L))
print("VO", list(zip(VO_FROM, DURS)))
