# Spoken words with absolute frames (60 fps) for the avatar word bubbles -> src/v42/words.ts
import json, re
VO_FROM = [8, 294, 521, 654, 849, 1088]
out = []
for i, base in enumerate(VO_FROM, 1):
    a = json.load(open(f"public/v42/vo/l{i}.json"))
    cur, t, inside = "", 0.0, False
    for c, s in list(zip(a["characters"], a["character_start_times_seconds"])) + [(" ", 0)]:
        if c == "[": inside = True
        if inside:
            if c == "]": inside = False
            continue
        if c.isspace():
            w = re.sub(r"[^\w-]", "", cur).replace("ё", "е").replace("Ё", "Е")
            if w: out.append((base + round(t * 60), w))
            cur = ""
        else:
            if not cur: t = s
            cur += c
# line 2: the voice swallows "с акцентом" (both words squeezed into ~2 frames) - no pills for words that are not heard
out = [(f, w) for f, w in out if not (294 < f < 360 and w in ("с", "акцентом"))]
L = ["// Generated by scripts/words-v42.py: every spoken word, absolute frame of its first letter.", "export const WORDS = ["]
L += [f'  {{ f: {f}, w: "{w}" }},' for f, w in out] + ["];", ""]
open("src/v42/words.ts", "w").write("\n".join(L))
print(len(out))
