# Four @the_tatarverse hosts (Ahu, Alicja, Kamilya, Alsu) for the "quad" series: copy every pose photo
# avatars/<host>/<NN>_<поза>.png -> public/quad/<host>/<latin>.png and write src/kit/quadFit.ts
# (per-photo scale so every photo fills the 540x590 box by height, like FIT_AHU in talk.tsx).
#   python scripts/quad-avatars.py
import os, shutil
from PIL import Image

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HOSTS = ["ahu", "alicja", "kamilya", "alsu"]
NAMES = {
    "00_нейтральная": "neutral", "01_задумчивая": "pensive", "02_мечтательная": "dreamy", "03_недовольная": "displeased",
    "04_удивление": "surprised", "05_радостно_машет": "waving", "06_вдохновение": "inspired", "06_объясняет": "explaining",
    "07_восторг": "delighted", "07_скепсис": "skeptical", "8_размышляет": "thinking", "9_сдержанная_улыбка": "soft-smile",
    "10_смех": "laughing", "11_недоумение": "puzzled", "12_разочарование": "disappointed", "14_улыбка_вверх": "smile-up",
    "16_указывает_вверх": "point-up", "17_указывает_вниз": "point-down", "18_показывает_влево": "present-left",
    "19_показывает_вправо": "point-right", "20_пожимает_плечами": "shrug", "21_рука_у_сердца": "hand-on-heart", "22_стоп": "stop",
    "23_палец_у_губ": "shush", "24_аплодирует": "clapping", "25_большой_палец": "thumbs-up", "26_скрещенные_руки": "arms-crossed",
    "27_фейспалм": "facepalm", "28_сердце_руками": "heart-hands", "29_победа": "victory", "30_слушает": "listening",
    "31_подмигивает": "wink", "32_смущение": "embarrassed", "33_тревога": "anxious", "34_испуг": "scared", "35_облегчение": "relieved",
    "36_гордость": "proud", "37_растрогана": "touched", "38_раздражение": "annoyed", "39_воздушный_поцелуй": "air-kiss",
    "40_сдерживает_смех": "holding-laugh", "41_притворно_плачет": "fake-cry", "42_закатывает_глаза": "eye-roll",
    "43_надула_щёки": "puffed-cheeks", "44_шепчет_секрет": "whisper", "45_зевает": "yawn", "46_отвращение": "disgust",
}
BOX = 540 / 590
fit = {}
for h in HOSTS:
    src, dst = os.path.join(root, "avatars", h), os.path.join(root, "public", "quad", h)
    os.makedirs(dst, exist_ok=True)
    fit[h] = {}
    readme = []
    for fn in sorted(os.listdir(src)):
        stem, ext = os.path.splitext(fn)
        if ext.lower() != ".png": continue
        if stem not in NAMES: raise SystemExit(f"unknown pose {h}/{fn}: add it to NAMES and to Emotion in TatAvatar.tsx")
        e = NAMES[stem]
        shutil.copyfile(os.path.join(src, fn), os.path.join(dst, f"{e}.png"))
        w, hh = Image.open(os.path.join(src, fn)).size
        fit[h][e] = round(max(1, w / hh / BOX), 3)
        readme.append(f"{e}.png <- avatars/{h}/{fn}")
    open(os.path.join(dst, "README.txt"), "w", encoding="utf-8").write("\n".join(readme) + "\n")
    print(h, len(fit[h]), "poses")

L = ["// Generated by scripts/quad-avatars.py: per-photo scale of each host's poses (public/quad/<host>/<pose>.png).",
     'import type { Emotion } from "./TatAvatar";', "",
     "export const QUAD_POSES: Record<QuadHost, Emotion[]> = {"]
for h in HOSTS: L.append(f"  {h}: [{', '.join(repr(e).replace(chr(39), chr(34)) for e in fit[h])}],")
L += ["};", "", "export type QuadHost = " + " | ".join(f'"{h}"' for h in HOSTS) + ";", "",
      "export const QUAD_FIT: Record<QuadHost, Partial<Record<Emotion, number>>> = {"]
for h in HOSTS: L.append(f"  {h}: {{ {', '.join(f'{chr(34)}{e}{chr(34)}: {v}' for e, v in fit[h].items() if v != 1)} }},")
L += ["};", ""]
open(os.path.join(root, "src", "kit", "quadFit.ts"), "w", encoding="utf-8").write("\n".join(L))
print("src/kit/quadFit.ts written")
