# Voice for the @the_tatarverse "talk" series (voice message + dialog of Ahu and Alicja).
# video/N-*/субтитры.txt: one line per reply, "who: [tags] text", who = ahu | alicja | man.
#   python3 scripts/talk.py N gen [3 5]   - Eleven v4 with timestamps -> public/vN/vo/raw/l<i>.mp3 + .json (all lines or the listed)
#   python3 scripts/talk.py N build [tempo] - trim silence (+ tempo), "voice message" filter on man lines,
#                                            lay lines out with dialog gaps -> src/vN/lines.ts (LINES: from, dur, who, words)
# Gaps: 14 frames between replies, 24 around the voice message; a line "gap: <frames>" in субтитры.txt overrides the next gap.
import base64, glob, json, os, re, subprocess, sys, urllib.request
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
N, cmd = sys.argv[1], sys.argv[2]
VOICE = {"ahu": "xyqF3vGMQlPk3e7yA4DI", "alicja": "iCzRDxXsrROcDYzWimM9", "man": "9AjtU6o19uipv7QL8dLL"}
folder = [d for d in glob.glob(os.path.join(root, f"video/{N}-*")) if os.path.isdir(d)][0]
rows = [l.strip() for l in open(os.path.join(folder, "субтитры.txt")) if l.strip()]
lines, gaps = [], {}
for r in rows:
    who, text = r.split(":", 1)
    if who == "gap": gaps[len(lines)] = int(text); continue
    lines.append((who.strip(), text.strip()))
vo = os.path.join(root, f"public/v{N}/vo")
os.makedirs(f"{vo}/raw", exist_ok=True)

if cmd == "gen":
    env = dict(l.strip().split("=", 1) for l in open(os.path.join(root, ".env")) if "=" in l)
    only = set(sys.argv[3:])
    for i, (who, text) in enumerate(lines, 1):
        if only and str(i) not in only: continue
        # the man is calmer and steadier; the hosts a bit livelier
        st = 0.6 if who == "man" else 0.5
        body = json.dumps({"text": text, "model_id": "eleven_v4", "language_code": "ru",
                           "voice_settings": {"stability": st, "similarity_boost": 0.75}}).encode()
        req = urllib.request.Request(f"https://api.elevenlabs.io/v1/text-to-speech/{VOICE[who]}/with-timestamps?output_format=mp3_44100_192",
                                     body, {"xi-api-key": env["ELEVENLABS_KEY"], "Content-Type": "application/json"})
        r = json.load(urllib.request.urlopen(req, timeout=180))
        open(f"{vo}/raw/l{i}.mp3", "wb").write(base64.b64decode(r["audio_base64"]))
        json.dump(r["normalized_alignment"] or r["alignment"], open(f"{vo}/raw/l{i}.json", "w"), ensure_ascii=False)
        print(f"l{i} {who} ok")

if cmd == "build":
    tempo = sys.argv[3] if len(sys.argv) > 3 else "1.0"
    subprocess.run(["python3", os.path.join(root, "scripts/trim-vo.py"), N, tempo], check=True, cwd=root)
    for i, (who, _) in enumerate(lines, 1):
        if who != "man": continue
        # a phone voice message: no lows, softened highs, a little room; zero-latency filters keep the timings
        tmp = f"{vo}/l{i}.tmp.mp3"
        subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", f"{vo}/l{i}.mp3", "-af",
                        "highpass=f=140,lowpass=f=7200,equalizer=f=2500:t=q:w=1:g=2,acompressor=threshold=-18dB:ratio=3:attack=5:release=80:makeup=2,alimiter=limit=0.89",
                        "-b:a", "192k", tmp], check=True)
        os.replace(tmp, f"{vo}/l{i}.mp3")
    f, out = 8, []
    for i, (who, _) in enumerate(lines, 1):
        d = float(subprocess.check_output(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", f"{vo}/l{i}.mp3"]))
        dur = round(d * 60)
        a = json.load(open(f"{vo}/l{i}.json"))
        cur, t, inside, words = "", 0.0, False, []
        for c, s in list(zip(a["characters"], a["character_start_times_seconds"])) + [(" ", 0)]:
            if c == "[": inside = True
            if inside:
                if c == "]": inside = False
                continue
            if c.isspace():
                w = re.sub(r"[^\w-]", "", cur).strip("-").replace("ё", "е").replace("Ё", "Е")
                if w: words.append((f + round(t * 60), w))
                cur = ""
            else:
                if not cur: t = s
                cur += c
        out.append((who, f, dur, words))
        print(f"l{i} {who} {f}+{dur}:", " ".join(f"{w}@{x}" for x, w in words))
        nxt = lines[i][0] if i < len(lines) else None
        gap = gaps.get(i, 24 if "man" in (who, nxt) else 14)
        f += dur + gap
    end = out[-1][1] + out[-1][2]
    print("last line ends", end)
    L = [f"// Generated by scripts/talk.py {N} build: every line with its start, length and words (absolute frames, 60 fps).",
         'import type { Line } from "../kit/talk";', "", "export const LINES: Line[] = ["]
    for i, (who, f0, dur, words) in enumerate(out, 1):
        ws = ", ".join(f'{{ f: {x}, w: "{w}" }}' for x, w in words)
        L.append(f'  {{ src: "v{N}/vo/l{i}.mp3", who: "{who}", from: {f0}, dur: {dur}, words: [{ws}] }},')
    L += ["];", "", f"export const END = {end};", ""]
    os.makedirs(os.path.join(root, f"src/v{N}"), exist_ok=True)
    open(os.path.join(root, f"src/v{N}/lines.ts"), "w").write("\n".join(L))
