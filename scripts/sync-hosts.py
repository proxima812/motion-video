# Copy every host photo avatars/<host>/<NN>_<ru>.png -> public/hosts/<host>/<latin>.png (same latin names as
# public/tatarverse/avatar/) and write src/kit/presets/fit.ts with the per-photo scale TatAvatar needs
# (wide photos are scaled up so every pose fills the 540x590 box by height, like FIT in src/v50/Video50.tsx).
# Re-run after adding photos to avatars/: python3 scripts/sync-hosts.py
import glob, os, re, shutil
from PIL import Image

HOSTS = ["ahu", "alicja", "kamilya", "alsu"]
LATIN = {
    "нейтральная": "neutral", "задумчивая": "pensive", "мечтательная": "dreamy", "недовольная": "displeased", "удивление": "surprised",
    "радостно_машет": "waving", "вдохновение": "inspired", "объясняет": "explaining", "восторг": "delighted", "скепсис": "skeptical",
    "размышляет": "thinking", "сдержанная_улыбка": "soft-smile", "смех": "laughing", "недоумение": "puzzled", "разочарование": "disappointed",
    "улыбка_вверх": "smile-up", "указывает_вверх": "point-up", "указывает_вниз": "point-down", "показывает_влево": "present-left",
    "показывает_вправо": "point-right", "пожимает_плечами": "shrug", "рука_у_сердца": "hand-on-heart", "стоп": "stop", "палец_у_губ": "shush",
    "аплодирует": "clapping", "большой_палец": "thumbs-up", "скрещенные_руки": "arms-crossed", "фейспалм": "facepalm", "сердце_руками": "heart-hands",
    "победа": "victory", "слушает": "listening", "подмигивает": "wink", "смущение": "embarrassed", "тревога": "anxious", "испуг": "scared",
    "облегчение": "relieved", "гордость": "proud", "растрогана": "touched", "раздражение": "annoyed", "воздушный_поцелуй": "air-kiss",
    "сдерживает_смех": "holding-laugh", "притворно_плачет": "fake-cry", "закатывает_глаза": "eye-roll", "надула_щёки": "puffed-cheeks",
    "шепчет_секрет": "whisper", "зевает": "yawn", "отвращение": "disgust",
}
BOX = 540 / 590

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
fit = {}
for host in HOSTS:
    out = os.path.join(root, "public/hosts", host)
    os.makedirs(out, exist_ok=True)
    readme, fit[host] = [], {}
    for src in sorted(glob.glob(os.path.join(root, "avatars", host, "*.png"))):
        ru = re.sub(r"^\d+_", "", os.path.splitext(os.path.basename(src))[0])
        name = LATIN[ru]  # KeyError = a new pose: add it here and to Emotion in src/kit/TatAvatar.tsx
        shutil.copyfile(src, os.path.join(out, f"{name}.png"))
        readme.append(f"{name}.png <- avatars/{host}/{os.path.basename(src)}")
        w, h = Image.open(src).size
        k = max(1, w / h / BOX)
        if k > 1.001: fit[host][name] = round(k, 3)
    open(os.path.join(out, "README.txt"), "w").write("\n".join(readme) + "\n")
    print(f"{host}: {len(readme)} poses")

L = ["// Generated by scripts/sync-hosts.py - per-photo scale for TatAvatar (wide photos fill the 540x590 box by height).",
     'import type { Emotion } from "../TatAvatar";', "",
     "export const HOST_FIT: Record<string, Partial<Record<Emotion, number>>> = {"]
for host in HOSTS:
    L.append(f"  {host}: {{ " + ", ".join(f'"{k}": {v}' for k, v in sorted(fit[host].items())) + " },")
L += ["};", ""]
open(os.path.join(root, "src/kit/presets/fit.ts"), "w").write("\n".join(L))
